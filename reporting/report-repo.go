// A report repository, as configured by ui-ldp at Settings -> Reporting ->
// Report repositories, and stored in mod-settings under scope "ui-ldp.admin",
// key "tqrepos". The value of that setting is an array of these.
type reportRepo struct {
	Type            string   `json:"type"`    // "github" or "gitlab"; empty means "github"
	BaseUrl         string   `json:"baseUrl"` // GitLab only; empty means https://gitlab.com
	User            string   `json:"user"`
	Repo            string   `json:"repo"`
	Branch          string   `json:"branch"`
	Dir             string   `json:"dir"`
	AuthorizedUsers []string `json:"authorizedUsers"` // UUIDs of users permitted to run reports
}

// A report repository that a report URL has been resolved to, together with
// the path of the report within that repository. If the URL names a commit by
// its SHA rather than naming the repository's branch, Commit is that SHA: in
// this case, the match holds only if the commit is on the branch, which is
// checked by verifyCommits.
type reportRepoMatch struct {
	Repo   reportRepo
	Path   string
	Commit string
}

func (rr reportRepo) String() string {
	t := rr.Type
	if t == "" {
		t = "github"
	}
	base := ""
	if rr.BaseUrl != "" {
		base = rr.BaseUrl + " "
	}
	return fmt.Sprintf("%s:%s%s/%s@%s:%s", t, base, rr.User, rr.Repo, rr.Branch, normalizeDir(rr.Dir))
}

type tqreposItem struct {
	// We don't care about id, scope or key
	Value json.RawMessage `json:"value"`
}

type tqreposResponse struct {
	Items      []tqreposItem      `json:"items"`
	ResultInfo settingsResultInfo `json:"resultInfo"`
}

// Fetches the list of configured report repositories from mod-settings. If
// none are configured, an empty list is returned.
func getReportRepos(session foliogo.Session, token string) ([]reportRepo, error) {
	params := foliogo.RequestParams{Token: token}
	bytes, err := session.Fetch("settings/entries?query=scope==%22ui-ldp.admin%22+and+key==%22tqrepos%22", params)
	if err != nil {
		return nil, fmt.Errorf("cannot fetch 'tqrepos' from settings: %w", err)
	}

	var r tqreposResponse
	err = json.Unmarshal(bytes, &r)
	if err != nil {
		return nil, fmt.Errorf("decode 'tqrepos' JSON failed: %w", err)
	}

	if r.ResultInfo.TotalRecords < 1 || len(r.Items) < 1 {
		return []reportRepo{}, nil
	}

	raw := r.Items[0].Value
	// If the value is encoded as a string: see issue #60
	var s string
	if json.Unmarshal(raw, &s) == nil {
		raw = []byte(s)
	}

	var repos []reportRepo
	err = json.Unmarshal(raw, &repos)
	if err != nil {
		return nil, fmt.Errorf("decode 'tqrepos' value failed: %w", err)
	}

	return repos, nil
}

// Normalizes a repository's directory in the same way that ui-ldp does (see
// src/util/resolveTemplatedQuery.js), so that both sides agree on what
// reports are in what repositories.
func normalizeDir(dir string) string {
	if dir == "" || dir == "/" || dir == "." {
		return "."
	}
	return strings.TrimRight(dir, "/")
}

var commitShaRegexp = regexp.MustCompile(`^[0-9a-fA-F]{40}$`)

// Determines whether reportUrl names a file within the specified repository,
// and if so returns the path of that file relative to the root of the
// repository. The URL forms recognized are those generated by rawFilePath()
// in ui-ldp's src/util/repoTypes.js, as these are what ui-ldp sends.
//
// If the URL names a commit by its SHA, that SHA is also returned: it is then
// up to the caller to check that the commit is on the repository's branch.
func (rr reportRepo) matchUrl(reportUrl string) (matches bool, filePath string, commit string) {
	u, err := url.Parse(reportUrl)
	if err != nil || u.Opaque != "" || u.User != nil {
		return false, "", ""
	}
	// Repositories are matched against the URL without its query and
	// fragment. The query, which matters only for GitLab, is checked
	// separately, by matchGitLabUrl. String() preserves the path's
	// original encoding, such as the %2F that is significant in GitLab
	// URLs.
	bare := *u
	bare.RawQuery = ""
	bare.ForceQuery = false
	bare.Fragment = ""
	bareUrl := bare.String()

	ok := false
	var encodedPath string
	switch rr.Type {
	case "", "github":
		ok, encodedPath, commit = rr.matchGitHubUrl(bareUrl)
	case "gitlab":
		ok, encodedPath = rr.matchGitLabUrl(bareUrl, u.RawQuery)
	}
	if !ok {
		return false, "", ""
	}

	filePath, err = url.PathUnescape(encodedPath)
	if err != nil || filePath == "" {
		return false, "", ""
	}
	// Refuse paths such as "dir/../elsewhere/report.sql" that might be
	// interpreted by the server as being outside the directory they appear
	// to be in.
	if path.Clean("/"+filePath) != "/"+filePath {
		return false, "", ""
	}

	dir := normalizeDir(rr.Dir)
	if dir != "." && !strings.HasPrefix(filePath, dir+"/") {
		return false, "", ""
	}

	return true, filePath, commit
}

// Determines whether bareUrl, which has no query or fragment, is a GitHub URL
// for a file in the specified repository, of the form
//
//	https://raw.githubusercontent.com/USER/REPO/REF/PATH
//
// where REF is the branch, either as a plain name or fully qualified as
// refs/heads/BRANCH, or the SHA of a commit. If so, returns the path, still
// URL-encoded, and, if REF is a SHA, that SHA.
func (rr reportRepo) matchGitHubUrl(bareUrl string) (matches bool, encodedPath string, commit string) {
	prefix := "https://raw.githubusercontent.com/" + rr.User + "/" + rr.Repo + "/"
	rest, ok := cutPrefixFold(bareUrl, prefix)
	if !ok {
		return false, "", ""
	}
	// The fully qualified form is checked first, so that it is not
	// mistaken for a branch named "refs".
	if after, ok := strings.CutPrefix(rest, "refs/heads/"+rr.Branch+"/"); ok {
		return true, after, ""
	}
	if after, ok := strings.CutPrefix(rest, rr.Branch+"/"); ok {
		return true, after, ""
	}

	// We cannot tell from the URL alone whether a commit is on the
	// configured branch, so any commit SHA matches here, and the caller
	// must ask GitHub (see verifyCommits).
	ref, after, found := strings.Cut(rest, "/")
	if !found || !commitShaRegexp.MatchString(ref) {
		return false, "", ""
	}
	return true, after, ref
}

// Determines whether bareUrl, which has no query or fragment, together with
// rawQuery, is a GitLab URL for a file in the specified repository, of the form
//
//	BASE/api/v4/projects/USER%2FREPO/repository/files/ENCODED-PATH/raw?ref=BRANCH
//
// If so, returns the path, still URL-encoded.
func (rr reportRepo) matchGitLabUrl(bareUrl string, rawQuery string) (matches bool, encodedPath string) {
	base := rr.BaseUrl
	if base == "" {
		base = "https://gitlab.com"
	}
	base = strings.TrimRight(base, "/")
	prefix := base + "/api/v4/projects/" + rr.User + "%2F" + rr.Repo + "/repository/files/"
	rest, ok := cutPrefixFold(bareUrl, prefix)
	if !ok {
		return false, ""
	}
	encodedPath, ok = strings.CutSuffix(rest, "/raw")
	if !ok {
		return false, ""
	}

	// The query must consist of exactly one ref parameter. In particular,
	// a URL such as ...?ref=dev&ref=other must be rejected, as we would see
	// the first ref but GitLab might use the last.
	q, err := url.ParseQuery(rawQuery)
	if err != nil || len(q) != 1 || len(q["ref"]) != 1 || q["ref"][0] != rr.Branch {
		return false, ""
	}
	return true, encodedPath
}

// Like strings.CutPrefix, but case-insensitive: hostnames, and GitHub and
// GitLab user and repository names, are all case-insensitive.
func cutPrefixFold(s string, prefix string) (string, bool) {
	if len(s) < len(prefix) || !strings.EqualFold(s[:len(prefix)], prefix) {
		return s, false
	}
	return s[len(prefix):], true
}

// Finds all the configured report repositories that contain the report at
// the specified URL. More than one may match, when one configured repository
// is in a subdirectory of another, or when the URL specifies a commit rather
// than a branch. Matches are returned in order of specificity, with those
// having the longest directory first. If none match, an empty list is
// returned: this happens, for example, when the URL is not in any of the
// recognized forms.
//
// Matches by commit SHA have not yet been checked against their repositories'
// branches: see verifyCommits.
func findReportRepos(repos []reportRepo, reportUrl string) []reportRepoMatch {
	matches := make([]reportRepoMatch, 0)
	for _, repo := range repos {
		if ok, filePath, commit := repo.matchUrl(reportUrl); ok {
			matches = append(matches, reportRepoMatch{Repo: repo, Path: filePath, Commit: commit})
		}
	}

	sort.SliceStable(matches, func(i, j int) bool {
		return len(normalizeDir(matches[i].Repo.Dir)) > len(normalizeDir(matches[j].Repo.Dir))
	})

	return matches
}

// Loads the configured report repositories and determines which, if any,
// contain the report at the specified URL.
func (session *ModReportingSession) findReportRepos(reportUrl string, token string) ([]reportRepoMatch, error) {
	repos, err := getReportRepos(session.folioSession, token)
	if err != nil {
		return nil, err
	}
	return findReportRepos(repos, reportUrl), nil
}

// The base URL of the GitHub API, which is used to check whether a commit is
// on a branch. A variable rather than a constant so that tests can point it
// at a mock server.
var githubApiUrl = "https://api.github.com"

// Determines whether the commit with the specified SHA is on the specified
// branch of a GitHub repository: that is, whether it is the head of the
// branch or one of its ancestors. This uses GitHub's compare API: comparing
// BRANCH...SHA yields "identical" if the commit is the head of the branch,
// "behind" if it is an ancestor, and "ahead" or "diverged" if it is not on
// the branch. GitHub responds 404 if there is no such commit.
func commitIsOnBranch(user string, repo string, branch string, sha string) (bool, error) {
	// Each part of the branch name is escaped separately, as GitHub
	// expects the slashes in a branch name such as "feature/x" to be
	// left as they are.
	branchParts := strings.Split(branch, "/")
	for i, part := range branchParts {
		branchParts[i] = url.PathEscape(part)
	}
	compareUrl := githubApiUrl + "/repos/" + url.PathEscape(user) + "/" + url.PathEscape(repo) +
		"/compare/" + strings.Join(branchParts, "/") + "..." + sha + "?per_page=1"

	client := makeFetchClient()
	resp, err := client.Get(compareUrl)
	if err != nil {
		return false, fmt.Errorf("could not ask GitHub whether commit %s is on branch %s of %s/%s: %w", sha, branch, user, repo, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode == http.StatusNotFound {
		return false, nil
	}
	if resp.StatusCode != http.StatusOK {
		return false, fmt.Errorf("could not ask GitHub whether commit %s is on branch %s of %s/%s: %s", sha, branch, user, repo, resp.Status)
	}

	var comparison struct {
		Status string `json:"status"`
	}
	err = json.NewDecoder(resp.Body).Decode(&comparison)
	if err != nil {
		return false, fmt.Errorf("could not decode GitHub's comparison of commit %s with branch %s of %s/%s: %w", sha, branch, user, repo, err)
	}
	return comparison.Status == "identical" || comparison.Status == "behind", nil
}

// Removes from matches those that name a commit by SHA, when that commit is
// not on the branch of the matching repository. Those that name the branch
// are kept without checking. GitHub is asked only once about each branch.
// Returns an error if GitHub cannot be asked, since the matches cannot then
// be trusted.
func (session *ModReportingSession) verifyCommits(matches []reportRepoMatch) ([]reportRepoMatch, error) {
	type branchKey struct {
		user   string
		repo   string
		branch string
	}
	onBranch := map[branchKey]bool{}

	verified := make([]reportRepoMatch, 0, len(matches))
	for _, m := range matches {
		if m.Commit == "" {
			verified = append(verified, m)
			continue
		}

		key := branchKey{strings.ToLower(m.Repo.User), strings.ToLower(m.Repo.Repo), m.Repo.Branch}
		ok, checked := onBranch[key]
		if !checked {
			var err error
			ok, err = commitIsOnBranch(m.Repo.User, m.Repo.Repo, m.Repo.Branch, m.Commit)
			if err != nil {
				return nil, err
			}
			onBranch[key] = ok
			session.Log("repo", fmt.Sprintf("commit %s is on branch %s of %s/%s: %t", m.Commit, m.Repo.Branch, m.Repo.User, m.Repo.Repo, ok))
		}
		if ok {
			verified = append(verified, m)
		}
	}
	return verified, nil
}

// Determines whether the user with the specified ID may run a report that is
// in all of the specified repositories, of which there must be at least one.
// The user may run it if any of the repositories permits it: that is, if any
// has no authorized users, and is therefore open to all, or lists the user
// among its authorized users. The user ID is needed only if all of the
// repositories are restricted.
//
// Returns nil if the report may be run. Otherwise, returns an error whose
// message says why not: either the user is not authorized, or there is no
// user ID to check.
func checkAccess(matches []reportRepoMatch, userId string) error {
	for _, m := range matches {
		if len(m.Repo.AuthorizedUsers) == 0 {
			return nil
		}
	}

	names := make([]string, len(matches))
	for i, m := range matches {
		names[i] = m.Repo.String()
	}
	repoList := strings.Join(names, " or ")

	if userId == "" {
		return fmt.Errorf("request has no X-Okapi-User-Id header, so cannot check whether the user is authorized to run reports from repository %s", repoList)
	}

	for _, m := range matches {
		if slices.Contains(m.Repo.AuthorizedUsers, userId) {
			return nil
		}
	}

	return fmt.Errorf("user %s is not authorized to run reports from repository %s", userId, repoList)
}
